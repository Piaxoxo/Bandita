/*
  Writes lib/image-dimensions.ts — every bitmap under public/ with its real
  pixel size.

  next/image needs an intrinsic size. For a fixed box (`fill`) the CSS supplies
  it, but the portfolio viewers lay their media out in the document flow, where
  the file's own aspect ratio is the layout. Hard-coding one ratio there would
  be wrong for every portrait shot in a landscape set, and reserving the wrong
  box is exactly what produces layout shift.

  So the sizes are read off the files at build time rather than guessed. Run
  this after adding or replacing images:

      node scripts/gen-image-dimensions.mjs
*/
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import sharp from "sharp";

const ROOT = "public";
const OUT = "lib/image-dimensions.ts";
const RE = /\.(jpe?g|png|webp|avif)$/i;

function walk(dir) {
  const found = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) found.push(...walk(p));
    else if (RE.test(name)) found.push(p);
  }
  return found;
}

const files = walk(ROOT).sort();
const entries = [];
let skipped = 0;

for (const file of files) {
  try {
    const { width, height } = await sharp(file).metadata();
    if (!width || !height) {
      skipped++;
      continue;
    }
    // the public path, as the browser requests it
    const url = "/" + relative(ROOT, file).split(sep).join("/");
    entries.push([url, width, height]);
  } catch {
    skipped++;
  }
}

const body = entries.map(([u, w, h]) => `  ${JSON.stringify(u)}: [${w}, ${h}],`).join("\n");

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-image-dimensions.mjs — do not edit by hand.
// Re-run it after adding or replacing anything in public/.

export const IMAGE_DIMENSIONS: Record<string, [number, number]> = {
${body}
};

/** Real pixel size of a public image, or null when it is not one of ours. */
export function dimsOf(src: string): { width: number; height: number } | null {
  const d = IMAGE_DIMENSIONS[src];
  return d ? { width: d[0], height: d[1] } : null;
}
`,
  "utf8",
);

console.log(`${entries.length} Bilder vermessen, ${skipped} übersprungen → ${OUT}`);
